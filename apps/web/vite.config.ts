import { defineConfig } from 'vite';
import react from '@vitejs/plugin-react';
import tailwindcss from '@tailwindcss/vite';
import { VitePWA } from 'vite-plugin-pwa';
import pkg from './package.json' with { type: 'json' };

export default defineConfig({
  // The app version, available in code as __APP_VERSION__ (used to invalidate the offline cache).
  define: { __APP_VERSION__: JSON.stringify(pkg.version) },
  plugins: [
    react(),
    tailwindcss(),
    /**
     * PROGRESSIVE WEB APP
     * - The MANIFEST lets phones "install" CrisisLink: home-screen icon, opens full screen.
     * - The SERVICE WORKER (generated by Workbox) is a script the browser keeps running between
     *   visits. It sits between the page and the network and serves the app's own files
     *   (HTML, JS, CSS, icons) from a local cache, so the app opens with no signal at all.
     *
     * API data is deliberately NOT cached here: TanStack Query persists it instead (see
     * src/lib/query-client.ts), because only it knows which data is public and which is
     * personal (evacuee lists must not stay on a shared phone after logout).
     */
    VitePWA({
      registerType: 'prompt', // ask before swapping to a new version mid-task
      includeAssets: ['favicon.svg', 'favicon.ico', 'apple-touch-icon-180x180.png'],
      manifest: {
        name: 'CrisisLink - Kerala relief coordination',
        short_name: 'CrisisLink',
        description: 'Relief camps, needs, incidents and volunteers for Kerala - works offline.',
        lang: 'en-IN',
        start_url: '/',
        display: 'standalone',
        theme_color: '#0f172a',
        background_color: '#f8fafc',
        icons: [
          { src: 'pwa-64x64.png', sizes: '64x64', type: 'image/png' },
          { src: 'pwa-192x192.png', sizes: '192x192', type: 'image/png' },
          { src: 'pwa-512x512.png', sizes: '512x512', type: 'image/png' },
          {
            src: 'maskable-icon-512x512.png',
            sizes: '512x512',
            type: 'image/png',
            purpose: 'maskable',
          },
        ],
        shortcuts: [
          { name: 'Report an emergency', url: '/report' },
          { name: 'Needs', url: '/needs' },
        ],
      },
      workbox: {
        // PRECACHE: every built file is downloaded once in the background, including lazy
        // page chunks and Leaflet, so every page opens offline - not just ones visited before.
        globPatterns: ['**/*.{js,css,html,svg,png,ico,woff2}'],
        // Any app URL (/camps/123) served offline from index.html; React Router takes over.
        navigateFallback: '/index.html',
        navigateFallbackDenylist: [/^\/api\//, /^\/socket\.io\//],
        cleanupOutdatedCaches: true,
        runtimeCaching: [
          {
            // Map tiles: CACHE FIRST - images of the same place don't change often, and
            // tiles of the area you looked at keep working offline.
            urlPattern: /^https:\/\/tile\.openstreetmap\.org\/.*/,
            handler: 'CacheFirst',
            options: {
              cacheName: 'map-tiles',
              expiration: { maxEntries: 800, maxAgeSeconds: 14 * 24 * 60 * 60 },
              cacheableResponse: { statuses: [0, 200] },
            },
          },
        ],
      },
      // Service workers + hot reload fight each other: test the PWA with `npm run preview`.
      devOptions: { enabled: false },
    }),
  ],
  server: {
    port: 5173,
    // In development the browser calls /api/... on the Vite server, which forwards
    // it to the API. Same origin for the browser = no CORS headaches locally.
    proxy: {
      '/api': 'http://localhost:4000',
      // Live updates: `ws: true` forwards the WebSocket upgrade, not just plain HTTP.
      '/socket.io': { target: 'http://localhost:4000', ws: true },
    },
  },
  // `npm run preview` serves the production build (with the service worker) on :4173.
  preview: {
    port: 4173,
    proxy: {
      '/api': 'http://localhost:4000',
      '/socket.io': { target: 'http://localhost:4000', ws: true },
    },
  },
});
